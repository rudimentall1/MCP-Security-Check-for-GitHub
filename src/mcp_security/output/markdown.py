"""GitHub PR-friendly Markdown report."""

from __future__ import annotations

from mcp_security.model.report import Decision, Report

_SEVERITY_EMOJI = {
    "critical": "🔴",
    "high": "🟠",
    "medium": "🟡",
    "low": "🔵",
    "info": "⚪",
}

_DECISION_HEADER = {
    Decision.BLOCK: "🔴 HIGH RISK",
    Decision.WARN: "🟡 NEEDS REVIEW",
    Decision.ALLOW: "🟢 LOW RISK",
}

_CAP_RISK_LABEL = {
    "shell.execute": "CRITICAL",
    "filesystem.write": "CRITICAL",
    "filesystem.delete": "CRITICAL",
    "network.unrestricted": "HIGH",
    "network.external": "HIGH",
    "secrets.read": "HIGH",
    "credentials.read": "HIGH",
    "package.install": "MEDIUM",
    "package.execute": "MEDIUM",
    "github.admin": "HIGH",
    "github.write": "MEDIUM",
}


def render_markdown(report: Report) -> str:
    lines = []
    lines.append("## 🛡️ MCP Security Check")
    lines.append("")
    lines.append(f"### {_DECISION_HEADER.get(report.decision, report.decision.value)}")
    lines.append("")
    lines.append(f"**Decision:** {report.decision.value}")
    lines.append("")
    lines.append(f"**Risk Score:** {report.risk_score}/100")
    lines.append("")

    summary = report.summary()
    lines.append("| Severity | Count |")
    lines.append("|---|---|")
    for sev in ("critical", "high", "medium", "low", "info"):
        lines.append(f"| {_SEVERITY_EMOJI[sev]} {sev.capitalize()} | {summary.get(sev, 0)} |")
    lines.append("")

    if report.capability_diff and (
        report.capability_diff.added or report.capability_diff.removed or report.capability_diff.changed
    ):
        lines.append("### Permission Changes")
        lines.append("")
        lines.append("| Capability | Change | Risk |")
        lines.append("|---|---|---|")
        for cap in report.capability_diff.added:
            risk = _CAP_RISK_LABEL.get(cap, "INFO")
            lines.append(f"| {cap} | NEW | {risk} |")
        for cap in report.capability_diff.removed:
            lines.append(f"| {cap} | REMOVED | - |")
        for change in report.capability_diff.changed:
            lines.append(
                f"| {change['capability']} | CHANGED ({change['before_target']} → {change['after_target']}) | - |"
            )
        lines.append("")

    if report.attack_paths:
        lines.append("### Attack Paths")
        lines.append("")
        for path in report.attack_paths:
            emoji = _SEVERITY_EMOJI.get(path.severity.value, "⚪")
            lines.append(f"{emoji} {path.chain_str()}")
            lines.append("")
            lines.append(path.description)
            lines.append("")

    if report.findings:
        lines.append("### Findings")
        lines.append("")
        for finding in report.findings:
            location = f" ({finding.file})" if finding.file else ""
            lines.append(f"- **{finding.rule_id}** {finding.title}{location}")
        lines.append("")

    lines.append("### Recommendation")
    lines.append("")
    if report.decision == Decision.BLOCK:
        lines.append("Review newly introduced capabilities before merging. This pull request is currently blocked by policy.")
    elif report.decision == Decision.WARN:
        lines.append("Review the findings above before merging.")
    else:
        lines.append("No blocking issues detected.")
    lines.append("")

    lines.append(
        "<sub>This report describes dangerous *capabilities*, not proof of malicious "
        "intent. Generated by MCP Security Check.</sub>"
    )

    return "\n".join(lines) + "\n"
